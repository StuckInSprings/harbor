const { app } = require('electron')
const fs = require('fs')
const path = require('path')

const TMP = '/tmp/harbor-store-test'
fs.rmSync(TMP, { recursive: true, force: true })
fs.mkdirSync(TMP, { recursive: true })
app.setPath('userData', TMP)

app.whenReady().then(async () => {
  const { db, blobs, keychain, maintenance } = require('../out/test/entry.cjs')
  let pass = 0, fail = 0
  const check = (label, ok, detail = '') => {
    console.log((ok ? 'ok    ' : 'FAIL  ') + label + (ok || !detail ? '' : ' -- ' + detail))
    ok ? pass++ : fail++
  }
  const Database = require('better-sqlite3')

  console.log('-- the schema is stamped and indexed --')
  db.initDb()
  const raw = new Database(path.join(TMP, 'harbor.db'), { readonly: true })
  check('user_version says which shape the file has', raw.pragma('user_version', { simple: true }) === db.SCHEMA_VERSION)
  const indexes = raw.prepare("SELECT name FROM sqlite_master WHERE type = 'index'").all().map((r) => r.name)
  check('the scanning queries have indexes', ['idx_msg_parent', 'idx_msg_created', 'idx_conv_run', 'idx_cp_path'].every((i) => indexes.includes(i)), indexes.join(' '))
  check('the file passes its own check', raw.pragma('quick_check', { simple: true }) === 'ok')
  raw.close()

  console.log('\n-- a blob is named by its hash, never by a path --')
  const hash = await blobs.put('hello')
  check('a stored blob reads back', (await blobs.getText(hash)) === 'hello')
  check('a hash is sixty-four hex characters', blobs.isHash(hash) && !blobs.isHash('../harbor.db') && !blobs.isHash(hash.toUpperCase()) && !blobs.isHash(''))
  check('a path in place of a hash reads as nothing', (await blobs.getBuffer('../harbor.db')) === null && (await blobs.getText('../harbor.db')) === null)
  fs.writeFileSync(path.join(TMP, 'blobs', 'not-a-hash'), 'x')
  check('nor does a file in the store folder under another name', (await blobs.getText('not-a-hash')) === null)

  console.log('\n-- the store keeps what is referenced and no more --')
  const proj = db.createProject('gc', null)
  const conv = db.createConversation(proj.id, 'x/y')
  const kept1 = await blobs.put('attached bytes')
  const kept2 = await blobs.put('snapshot after')
  const kept3 = await blobs.put('snapshot before')
  const stray = await blobs.put('nobody points here')
  const stale = await blobs.put('an old snapshot')
  {
    const labelled = db.addMessage(conv.id, null, 'assistant', 'hot take', 'm/m', { label: 't=1.4' })
    const plain = db.addMessage(conv.id, null, 'assistant', 'cool take', 'm/m')
    const rows = db.listMessages(conv.id)
    check('a fanned-out reply keeps the variant it was asked as; an ordinary one has none', rows.find((m) => m.id === labelled.id).label === 't=1.4' && rows.find((m) => m.id === plain.id).label === null)
    const copied = db.copyMessage(labelled, null)
    check('and a copy carries it', copied.label === 't=1.4')
  }
  {
    const a = db.createProject('Order A', null), b = db.createProject('Order B', null), c = db.createProject('Order C', null)
    const order = () => db.listProjects().map((p) => p.name).filter((n) => n.startsWith('Order '))
    check('projects never placed come oldest first', order().join('|') === 'Order A|Order B|Order C')
    db.reorderProjects([c.id, a.id, b.id])
    check('a reorder is kept', order().join('|') === 'Order C|Order A|Order B')
    const d = db.createProject('Order D', null)
    check('a new project goes after the placed ones', order().join('|') === 'Order C|Order A|Order B|Order D')
    check('a new project is not archived', db.listProjects().find((p) => p.id === d.id).archived === false)
    db.setProjectArchived(d.id, true)
    check('archiving is kept, and the project stays listed for the archive section', db.listProjects().find((p) => p.id === d.id).archived === true)
    db.setProjectArchived(d.id, false)
    check('and undone', db.listProjects().find((p) => p.id === d.id).archived === false)
  }
  db.addMessage(conv.id, null, 'user', 'see', null, { attachments: JSON.stringify([{ hash: kept1, name: 'a.txt', mime: 'text/plain', kind: 'text', size: 14 }]) })
  db.addCheckpoint({ runId: 'r1', conversationId: conv.id, path: 'a.md', beforeHash: kept3, afterHash: kept2, created: false, webUsed: false })
  const oldCp = db.addCheckpoint({ runId: 'r0', conversationId: conv.id, path: 'b.md', beforeHash: null, afterHash: stale, created: true, webUsed: false })
  const rw = new Database(path.join(TMP, 'harbor.db'))
  rw.prepare('UPDATE checkpoints SET created_at = ? WHERE id = ?').run(Date.now() - 200 * 24 * 3_600_000, oldCp)
  rw.close()
  const refs = db.referencedBlobs()
  check('references come from attachments and both sides of a checkpoint', refs.has(kept1) && refs.has(kept2) && refs.has(kept3) && refs.has(stale) && !refs.has(stray))
  const done = await maintenance.housekeep()
  check('a checkpoint past the retention window is pruned', done.pruned === 1 && db.getCheckpoint(oldCp) === null)
  check('blobs nobody references are swept, including the pruned snapshot and the hello from above', done.removed === 3 && (await blobs.getText(stray)) === null && (await blobs.getText(stale)) === null, JSON.stringify(done))
  check('what is referenced stays', (await blobs.getText(kept1)) === 'attached bytes' && (await blobs.getText(kept2)) === 'snapshot after' && (await blobs.getText(kept3)) === 'snapshot before')
  check('a file in the store folder that is not a hash is not touched', fs.existsSync(path.join(TMP, 'blobs', 'not-a-hash')))
  db.setSetting(maintenance.RETENTION_SETTING, '0')
  check('a retention of zero keeps every checkpoint', maintenance.retentionDays() === 0 && db.pruneCheckpoints(0) === 0)
  db.setSetting(maintenance.RETENTION_SETTING, '')
  check('an empty setting is the default', maintenance.retentionDays() === maintenance.DEFAULT_RETENTION_DAYS)

  console.log('\n-- the key is present only when there is one --')
  check('no key at first', keychain.hasKey() === false)
  keychain.clearKey()
  check('clearing when there is none leaves none', keychain.hasKey() === false)
  db.setSetting('openrouter_key_encrypted', 'c2VjcmV0')
  check('a stored key counts', keychain.hasKey() === true)
  keychain.clearKey()
  check('a cleared key is gone', keychain.hasKey() === false && keychain.readKey() === null)

  console.log(`\n${pass} passed, ${fail} failed`)
  app.exit(fail === 0 ? 0 : 1)
}).catch((e) => { console.log('THREW ' + e.stack); app.exit(1) })
