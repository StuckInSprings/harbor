const { app } = require('electron')
const fs = require('fs')
const path = require('path')
const { execFileSync } = require('child_process')

const TMP = '/tmp/harbor-shadow-test'
fs.rmSync(TMP, { recursive: true, force: true })
fs.mkdirSync(path.join(TMP, 'proj', 'src'), { recursive: true })
app.setPath('userData', TMP)

app.whenReady().then(async () => {
  const { db, shadow, worktrees } = require('../out/test/entry.cjs')
  let pass = 0, fail = 0
  const check = (label, ok, detail = '') => {
    console.log((ok ? 'ok    ' : 'FAIL  ') + label + (ok || !detail ? '' : ' -- ' + detail))
    ok ? pass++ : fail++
  }
  db.initDb()
  const root = path.join(TMP, 'proj')
  const w = (rel, text) => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text) }
  const r = (rel) => fs.existsSync(path.join(root, rel)) ? fs.readFileSync(path.join(root, rel), 'utf8') : null

  console.log('-- the shadow repository --')
  w('src/a.txt', 'one\n')
  w('.gitignore', 'build/\n')
  w('src/c.txt', 'to go\n')
  w('build/out.bin', 'built')
  w('node_modules/x/index.js', 'dep')
  w('.env', 'SECRET=1')
  const s1 = await shadow.snapshot('p1', root, 'before turn 1')
  check('a snapshot is a sha', typeof s1 === 'string' && /^[0-9a-f]{40}$/.test(s1), String(s1))
  check('the repository lives under Application Support, not the project', fs.existsSync(path.join(TMP, 'shadow', 'p1', 'HEAD')) && !fs.existsSync(path.join(root, '.git')))
  // The shell writes, renames and deletes; nothing but the tree records it.
  w('src/a.txt', 'two\n')
  w('src/b.txt', 'new\n')
  fs.unlinkSync(path.join(root, 'src/c.txt'))
  const s2 = await shadow.snapshot('p1', root, 'after turn 1')
  const changed = await shadow.changed('p1', root, s1, s2)
  const by = Object.fromEntries(changed.map((c) => [c.path, c.status]))
  check('the diff between snapshots names what the shell did', by['src/a.txt'] === 'M' && by['src/b.txt'] === 'A' && by['src/c.txt'] === 'D', JSON.stringify(changed))
  check('ignored, dependency and secret files are not in it', !changed.some((c) => /build\/|node_modules|\.env/.test(c.path)) && (await shadow.fileAt('p1', root, s2, '.env')) === null && (await shadow.fileAt('p1', root, s2, 'node_modules/x/index.js')) === null)
  check('a file as it was in a snapshot', (await shadow.fileAt('p1', root, s1, 'src/a.txt')) === 'one\n' && (await shadow.fileAt('p1', root, s1, 'src/b.txt')) === null)
  const s3 = await shadow.snapshot('p1', root, 'nothing changed')
  check('an unchanged tree still gets a snapshot of its own', s3 && s3 !== s2 && (await shadow.changed('p1', root, s2, s3)).length === 0)

  console.log('\n-- restoring the tree --')
  const safety = await shadow.restore('p1', root, s1)
  check('the tree is as it was: the edit undone, the new file gone, the deleted one back', r('src/a.txt') === 'one\n' && r('src/b.txt') === null && r('src/c.txt') === 'to go\n')
  check('what the snapshots never held is untouched', r('build/out.bin') === 'built' && r('node_modules/x/index.js') === 'dep' && r('.env') === 'SECRET=1')
  check('a safety snapshot was taken first, and holds the state before the restore', typeof safety === 'string' && (await shadow.fileAt('p1', root, safety, 'src/b.txt')) === 'new\n')
  await shadow.restore('p1', root, safety)
  check('and restoring to it brings that state back', r('src/b.txt') === 'new\n' && r('src/a.txt') === 'two\n')
  check('every snapshot is tagged, so nothing loses it', execFileSync('git', ['--git-dir', path.join(TMP, 'shadow', 'p1'), 'tag'], { encoding: 'utf8' }).includes('s-' + s1.slice(0, 12)))

  console.log('\n-- the rows --')
  const p = db.createProject('Shadowed', root)
  const c = db.createConversation(p.id, 'm', false)
  db.addSnapshot({ runId: 'turn-1', conversationId: c.id, projectId: p.id, kind: 'before', sha: s1 })
  db.addSnapshot({ runId: 'turn-1', conversationId: c.id, projectId: p.id, kind: 'after', sha: s2 })
  const rows = db.listSnapshots(c.id)
  check('snapshots are listed for the conversation, newest first', rows.length === 2 && rows[0].kind === 'after' && rows[1].sha === s1 && db.getSnapshot(rows[0].id).runId === 'turn-1', JSON.stringify(rows))
  check('the schema is at 12', db.SCHEMA_VERSION === 12)

  console.log('\n-- a worktree per worker --')
  const repo = path.join(TMP, 'repo')
  fs.mkdirSync(repo, { recursive: true })
  const g = (...args) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', ...args], { cwd: repo, encoding: 'utf8' }).trim()
  g('init', '-q', '-b', 'main')
  fs.writeFileSync(path.join(repo, 'README.md'), 'hello\n')
  g('add', '-A'); g('commit', '-q', '-m', 'first')
  g('checkout', '-q', '-b', 'harbor/run-1')
  const wt = await worktrees.create(repo, 'harbor/run-1', 'T1-1')
  check('the worktree is under Application Support on a branch from the run', wt.path.startsWith(path.join(TMP, 'worktrees')) && wt.branch === 'harbor/run-1-t1-1' && fs.readFileSync(path.join(wt.path, 'README.md'), 'utf8') === 'hello\n', JSON.stringify(wt))
  worktrees.setRoot('conv-1', wt.path)
  check('the conversation is rooted there while it runs', worktrees.rootOverride('conv-1') === wt.path && worktrees.rootOverride('other') === null)
  fs.writeFileSync(path.join(wt.path, 'src.txt'), 'made by the worker\n')
  fs.writeFileSync(path.join(wt.path, 'README.md'), 'hello\nand more\n')
  check('the main tree does not see the worker\'s half-done files', !fs.existsSync(path.join(repo, 'src.txt')))
  const f = await worktrees.fold(repo, wt, 'T1: the task')
  check('folding commits and merges into the run branch', f.merged && f.commit && f.files.join(',') === 'README.md,src.txt', JSON.stringify(f))
  check('the run branch has the work and a merge commit', fs.readFileSync(path.join(repo, 'src.txt'), 'utf8') === 'made by the worker\n' && g('log', '--oneline', '-1').includes('T1: the task') && g('rev-parse', '--abbrev-ref', 'HEAD') === 'harbor/run-1')
  check('the worktree and its branch are gone', !fs.existsSync(wt.path) && !g('branch', '--list').includes('t1-1'))
  worktrees.setRoot('conv-1', null)
  check('and the root override with them', worktrees.rootOverride('conv-1') === null)

  const wt2 = await worktrees.create(repo, 'harbor/run-1', 'T2-1')
  const f2 = await worktrees.fold(repo, wt2, 'T2: nothing')
  check('a worker that changed nothing folds to nothing, and is cleaned up', f2.merged && f2.commit === null && f2.files.length === 0 && !fs.existsSync(wt2.path))

  const wt3 = await worktrees.create(repo, 'harbor/run-1', 'T3-1')
  fs.writeFileSync(path.join(wt3.path, 'README.md'), 'the worker\'s version\n')
  fs.writeFileSync(path.join(repo, 'README.md'), 'the person\'s uncommitted version\n')
  const f3 = await worktrees.fold(repo, wt3, 'T3: clash')
  check('a merge the main tree cannot take is refused, with a reason, and nothing is lost', !f3.merged && f3.reason && fs.readFileSync(path.join(repo, 'README.md'), 'utf8') === 'the person\'s uncommitted version\n' && fs.existsSync(wt3.path) && g('branch', '--list', 'harbor/run-1-t3-1').includes('t3-1'), JSON.stringify(f3))
  check('the merge was abandoned cleanly', !fs.existsSync(path.join(repo, '.git', 'MERGE_HEAD')))
  await worktrees.remove(repo, wt3, true)
  fs.writeFileSync(path.join(repo, 'README.md'), 'hello\nand more\n')

  g('checkout', '-q', 'main')
  const wt4 = await worktrees.create(repo, 'harbor/run-1', 'T4-1')
  fs.writeFileSync(path.join(wt4.path, 'four.txt'), '4\n')
  const f4 = await worktrees.fold(repo, wt4, 'T4: moved')
  check('when the person has left the run branch, the work stays on its own branch and says so', !f4.merged && /main, not harbor\/run-1/.test(f4.reason) && g('branch', '--list', 'harbor/run-1-t4-1').includes('t4-1'), JSON.stringify(f4))
  await worktrees.remove(repo, wt4, true)

  console.log(`\n${pass} passed, ${fail} failed`)
  app.exit(fail ? 1 : 0)
})
